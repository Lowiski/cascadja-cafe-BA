// Generates database/seed.sql from the real Cascadja menu + deterministic
// sample transactions. Run: node scripts/generate-seed-sql.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateRealDataset } from '../src/data/generateRealData.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, '../../database/seed.sql');
const data = generateRealDataset();

const esc = (v) => {
  if (v === null || v === undefined || v === '') return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'TRUE' : 'FALSE';
  return `'${String(v).replace(/'/g, "''")}'`;
};

const MENU_ROWS = data.menu.map((m) => [
  m.id, m.name, m.category, m.priceHot, m.priceIced, m.bestseller,
]);
const ADDON_ROWS = data.addons.map((a) => [a.id, a.name, a.price, a.bestseller]);
const SALES_ROWS = data.sales.map((s) => [
  s.id, s.order_id, s.order_date, s.daypart, s.channel, s.product_category,
  s.item_name, s.item_price, s.quantity_sold, s.addon_name || null,
  s.addon_amount, s.total_sales,
]);

const TABLES = [
  ['menu_items', ['id', 'name', 'category', 'hot_price', 'iced_price', 'bestseller'], MENU_ROWS],
  ['addons', ['id', 'name', 'price', 'bestseller'], ADDON_ROWS],
  ['sales_fact', [
    'id', 'order_id', 'order_date', 'daypart', 'channel', 'product_category',
    'item_name', 'item_price', 'quantity_sold', 'addon_name', 'addon_amount', 'total_sales',
  ], SALES_ROWS],
];

const lines = [
  '-- Cascadja Foods and Drinks - deterministic SAMPLE transaction data.',
  '-- Menu names/prices are from the owner photos; transactions are generated (seed 20261120).',
  '-- Generated by backend/scripts/generate-seed-sql.mjs.',
  '',
  'BEGIN;',
  'TRUNCATE sales_fact, addons, menu_items RESTART IDENTITY CASCADE;',
  '',
];

for (const [table, columns, rows] of TABLES) {
  lines.push(`-- ${table}: ${rows.length} rows`);
  for (let i = 0; i < rows.length; i += 100) {
    const tuples = rows.slice(i, i + 100).map((row) => `  (${row.map(esc).join(', ')})`);
    lines.push(`INSERT INTO ${table} (${columns.join(', ')}) VALUES`);
    lines.push(`${tuples.join(',\n')};`);
  }
  lines.push(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE((SELECT MAX(id) FROM ${table}), 1));`);
  lines.push('');
}

lines.push('COMMIT;', '');
fs.writeFileSync(out, lines.join('\n'), 'utf8');
console.log(`Wrote ${out} (${fs.statSync(out).size.toLocaleString()} bytes)`);
